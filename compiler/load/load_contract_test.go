func TestLoadCancelsActivePackageDriver(t *testing.T) {
	executable, err := os.Executable()
	if err != nil {
		t.Fatalf("os.Executable(): %v", err)
	}
	dir := writeModule(t, map[string]string{
		"go.mod":     "module example.com/cancelactive\n\ngo 1.23.0\n",
		"app/app.go": "package app\n",
	})
	signalDir := t.TempDir()
	started := filepath.Join(signalDir, "started")
	pidFile := filepath.Join(signalDir, "pid")
	environment := os.Environ()
	environment = replaceEnvironmentValue(environment, "GOPACKAGESDRIVER", executable)
	environment = replaceEnvironmentValue(environment, blockingDriverMode, "1")
	environment = replaceEnvironmentValue(environment, "SPICE_TEST_DRIVER_STARTED", started)
	environment = replaceEnvironmentValue(environment, "SPICE_TEST_DRIVER_PID", pidFile)

	ctx, cancel := context.WithCancel(context.Background())
	result := make(chan struct {
		program *Program
		err     error
	}, 1)
	go func() {
		program, loadErr := Load(ctx, Options{Dir: dir, Env: environment}, "./...")
		result <- struct {
			program *Program
			err     error
		}{program: program, err: loadErr}
	}()

	waitForPath(t, started, 5*time.Second)
	cancel()
	select {
	case loaded := <-result:
		if !errors.Is(loaded.err, context.Canceled) {
			t.Fatalf("Load() error = %v, want context.Canceled", loaded.err)
		}
		if loaded.program != nil {
			t.Fatalf("Load() program = %#v, want nil", loaded.program)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("Load() did not return after cancelling an active package driver")
	}

	if runtime.GOOS == "linux" {
		pidBytes, err := os.ReadFile(pidFile)
		if err != nil {
			t.Fatalf("ReadFile(pid): %v", err)
		}
		pid, err := strconv.Atoi(strings.TrimSpace(string(pidBytes)))
		if err != nil {
			t.Fatalf("driver pid = %q: %v", pidBytes, err)
		}
		deadline := time.Now().Add(2 * time.Second)
		for {
			_, statErr := os.Stat(filepath.Join("/proc", strconv.Itoa(pid)))
			if os.IsNotExist(statErr) {
				break
			}
			if time.Now().After(deadline) {
				t.Fatalf("package driver process %d still exists after Load returned", pid)
			}
			time.Sleep(10 * time.Millisecond)
		}
	}
}

func waitForPath(t *testing.T, path string, timeout time.Duration) {
	t.Helper()
	deadline := time.Now().Add(timeout)
	for {
		if _, err := os.Stat(path); err == nil {
			return
		} else if !os.IsNotExist(err) {
			t.Fatalf("Stat(%q): %v", path, err)
		}
		if time.Now().After(deadline) {
			t.Fatalf("timed out waiting for %q", path)
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func requireCgo(t *testing.T) {
	t.Helper()
	output, err := exec.Command("go", "env", "CGO_ENABLED").Output()
	if err != nil {
		t.Fatalf("go env CGO_ENABLED: %v", err)
	}
	if strings.TrimSpace(string(output)) != "1" {
		t.Skip("cgo is disabled for this Go toolchain")
	}
	compilerOutput, err := exec.Command("go", "env", "CC").Output()
	if err != nil {
		t.Fatalf("go env CC: %v", err)
	}
	compilerFields := strings.Fields(string(compilerOutput))
	if len(compilerFields) == 0 {
		t.Skip("cgo C compiler is not configured")
	}
	if _, err := exec.LookPath(compilerFields[0]); err != nil {
		t.Skipf("cgo C compiler %q is unavailable", compilerFields[0])
	}
}

func TestLoadOmitsNonAddressableDeclarationsAndReturnsUniqueSymbolIDs(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/identity\n\ngo 1.23.0\n",
		"catalog/first.go": `package catalog

func init() {}

type _ int
func _() {}
var _ = 1
const _ = 2

type Service struct{}
func (Service) _() {}
func (Service) Start() {}

var First int
const FirstConstant = 3
`,
		"catalog/second.go": `package catalog

func init() {}

type _ string
func _() {}
var _ = 4
const _ = 5

func (Service) _() {}

func Build() *Service { return &Service{} }
const Second = 6
`,
	})

	program, err := Load(context.Background(), Options{Dir: dir}, "./...")
	if err != nil {
		t.Fatalf("Load() error = %v", err)
	}

	symbols := program.Symbols()
	assertUniqueSymbolIDs(t, symbols)
	if got, want := symbolIDs(symbols), []string{
		"example.com/identity/catalog",
		"example.com/identity/catalog.Build",
		"example.com/identity/catalog.First",
		"example.com/identity/catalog.FirstConstant",
		"example.com/identity/catalog.Second",
		"example.com/identity/catalog.Service",
		"example.com/identity/catalog.Service.Start",
	}; !reflect.DeepEqual(got, want) {
		t.Fatalf("symbol IDs = %v, want every non-addressable declaration omitted as %v", got, want)
	}
	for _, symbol := range symbols {
		if symbol.Name == "_" || symbol.Name == "init" {
			t.Fatalf("non-addressable %s declaration %q entered symbol catalog: %v", symbol.Kind, symbol.ID, symbolIDs(symbols))
		}
	}
}

func replaceEnvironmentValue(environment []string, name, value string) []string {
	prefix := name + "="
	result := make([]string, 0, len(environment)+1)
	for _, entry := range environment {
		if strings.HasPrefix(entry, prefix) {
			continue
		}
		result = append(result, entry)
	}
	return append(result, prefix+value)
}
