func TestLoadCgoUsesSourceDirectoryAndOmitsSyntheticSymbols(t *testing.T) {
	requireCgo(t)

	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/cgosource\n\ngo 1.23.0\n",
		"catalog/catalog.go": `package catalog

/*
static int answer(void) { return 42; }
*/
import "C"

type Service struct{}
var Value = int(C.answer())
func Build() *Service { return &Service{} }
`,
		"catalog/generated.go": `// Code generated by the Spice cgo fixture. DO NOT EDIT.
package catalog

const Generated = 7
`,
	})

	program, err := Load(context.Background(), Options{Dir: dir}, "./catalog")
	if err != nil {
		t.Fatalf("Load() error = %v", err)
	}

	packages := program.Packages()
	if len(packages) != 1 {
		t.Fatalf("packages = %#v, want one cgo package", packages)
	}
	pkg := packages[0]
	sourceDir := filepath.Join(dir, "catalog")
	if got, want := pkg.Dir, sourceDir; got != want {
		t.Fatalf("package directory = %q, want source directory %q", got, want)
	}
	if !sort.StringsAreSorted(pkg.CompiledGoFiles) {
		t.Fatalf("compiled Go files are not sorted: %v", pkg.CompiledGoFiles)
	}
	if len(pkg.Files) != len(pkg.CompiledGoFiles) || len(pkg.Syntax) != len(pkg.CompiledGoFiles) {
		t.Fatalf("file model lengths: files=%d compiled=%d syntax=%d", len(pkg.Files), len(pkg.CompiledGoFiles), len(pkg.Syntax))
	}
	for i, file := range pkg.Files {
		if file.PhysicalPath != pkg.CompiledGoFiles[i] || file.Syntax != pkg.Syntax[i] {
			t.Fatalf("file association %d = %#v, compiled=%q syntax=%p", i, file, pkg.CompiledGoFiles[i], pkg.Syntax[i])
		}
		if file.Syntax != nil {
			physical := filepath.Clean(pkg.Raw.Fset.PositionFor(file.Syntax.Pos(), false).Filename)
			if physical != file.PhysicalPath {
				t.Fatalf("file association %d physical syntax path = %q, want %q", i, physical, file.PhysicalPath)
			}
		}
	}
	hasCacheBackedInput := false
	for _, file := range pkg.CompiledGoFiles {
		if filepath.Dir(file) != sourceDir {
			hasCacheBackedInput = true
			break
		}
	}
	if !hasCacheBackedInput {
		t.Fatalf("compiled Go files = %v, want cgo cache-backed inputs proving integration path executed", pkg.CompiledGoFiles)
	}

	symbols := program.Symbols()
	assertUniqueSymbolIDs(t, symbols)
	if got, want := symbolIDs(symbols), []string{
		"example.com/cgosource/catalog",
		"example.com/cgosource/catalog.Build",
		"example.com/cgosource/catalog.Generated",
		"example.com/cgosource/catalog.Service",
		"example.com/cgosource/catalog.Value",
	}; !reflect.DeepEqual(got, want) {
		t.Fatalf("symbol IDs = %v, want source declarations only %v", got, want)
	}

	catalogSource := filepath.Join(sourceDir, "catalog.go")
	generatedSource := filepath.Join(sourceDir, "generated.go")
	wantPosition := map[string]string{
		"example.com/cgosource/catalog":           catalogSource,
		"example.com/cgosource/catalog.Build":     catalogSource,
		"example.com/cgosource/catalog.Generated": generatedSource,
		"example.com/cgosource/catalog.Service":   catalogSource,
		"example.com/cgosource/catalog.Value":     catalogSource,
	}
	for _, symbol := range symbols {
		filename := filepath.Clean(symbol.Position.Filename)
		if filename != wantPosition[symbol.ID] {
			t.Fatalf("symbol %q position = %q, want source file %q", symbol.ID, filename, wantPosition[symbol.ID])
		}
		if strings.Contains(symbol.Name, "_C") || strings.HasPrefix(symbol.Name, "_cgo") || strings.HasPrefix(symbol.Name, "__cgo") {
			t.Fatalf("cgo synthetic declaration entered symbol catalog: %q", symbol.ID)
		}
	}
}

func TestLoadRetainsLineMappedSourceWithPhysicalAndDisplayPositions(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/linemapped\n\ngo 1.23.0\n",
		"app/app.go": `package app

//line generated/schema.proto:40
var Value int
`,
	})

	program, err := Load(context.Background(), Options{Dir: dir}, "./app")
	if err != nil {
		t.Fatalf("Load() error = %v", err)
	}
	value := symbolByID(program.Symbols(), "example.com/linemapped/app.Value")
	if value == nil {
		t.Fatalf("line-mapped declaration missing: %v", symbolIDs(program.Symbols()))
	}
	physical := filepath.Join(dir, "app", "app.go")
	if got := filepath.Clean(value.PhysicalPosition.Filename); got != physical {
		t.Fatalf("physical filename = %q, want %q", got, physical)
	}
	display := filepath.Join(dir, "app", "generated", "schema.proto")
	if got := filepath.Clean(value.Position.Filename); got != display || value.Position.Line != 40 {
		t.Fatalf("display position = %s, want %s:40", value.Position, display)
	}
}

